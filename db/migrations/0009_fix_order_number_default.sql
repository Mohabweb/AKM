-- 0009_fix_order_number_default.sql
--
-- Fixes the checkout failure "We couldn't complete your request. Please try again."
--
-- Cause (confirmed from the server log and by probing the hosted project):
--   orders.order_number was created with an INLINE default that calls gen_random_bytes().
--   create_order() runs with `search_path = public`, but on hosted Supabase pgcrypto lives in the
--   `extensions` schema, so the INSERT ... RETURNING inside create_order failed with
--      42883  function gen_random_bytes(integer) does not exist
--   for every order, COD and InstaPay alike. Reading data (catalog, cart quote, rate limiting)
--   kept working, which is why only placing an order broke.
--
-- Fix: point the default back at public.gen_order_number(), whose own search_path includes the
-- extensions schema, and re-assert the service_role EXECUTE grants used by the API routes.
-- Safe to run more than once.

-- 1. Order numbers are generated by one function, never inline in a column default.
create or replace function public.gen_order_number() returns text
language plpgsql volatile set search_path = public, extensions, pg_catalog as $$
declare
  alphabet constant text := '0123456789ABCDEFGHJKMNPQRSTVWXYZ';
  bytes bytea;
  result text := 'AKM-';
  i int;
begin
  bytes := gen_random_bytes(6);
  for i in 0..5 loop
    result := result || substr(alphabet, (get_byte(bytes, i) % 32) + 1, 1);
  end loop;
  return result;
end $$;

alter table public.orders alter column order_number set default public.gen_order_number();

-- 2. Least-privilege grants the API depends on (idempotent).
grant execute on function public.gen_order_number() to service_role;
grant execute on function public.create_order(jsonb) to service_role;
grant execute on function public.quote_cart(jsonb) to service_role;
grant execute on function public.rate_limit_hit(text, int, int) to service_role;
grant execute on function public.attach_receipt(uuid, text) to service_role;
grant execute on function public.track_order(text, text) to service_role;
grant execute on function public.system_set_order_status(uuid, public.order_status, text, text) to service_role;
grant execute on function public.expire_unpaid_orders(int) to service_role;
grant execute on function public.setting_int(text, int) to service_role;
grant execute on function public.set_order_status(uuid, public.order_status, text) to authenticated, service_role;
grant execute on function public.review_receipt(uuid, boolean, text) to authenticated, service_role;

-- 3. Refuse to finish if the drift is still there, so the dashboard run cannot look "successful" while checkout stays broken.
do $$
declare expr text;
begin
  select pg_get_expr(d.adbin, d.adrelid) into expr
  from pg_attrdef d
  join pg_attribute a on a.attrelid = d.adrelid and a.attnum = d.adnum
  where d.adrelid = 'public.orders'::regclass and a.attname = 'order_number';
  if expr is null or expr not like '%gen_order_number%' then
    raise exception 'orders.order_number default was not repaired (found: %)', coalesce(expr, 'none');
  end if;
end $$;
